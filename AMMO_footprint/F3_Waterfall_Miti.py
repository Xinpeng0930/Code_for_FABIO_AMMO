def plot_absolute(df: pd.DataFrame, outdir: Path):
    n = len(df)
    x = np.arange(n)
    bar_width = 0.36
    group_gap = 0.04
    offset = (bar_width + group_gap) / 2

    fig = plt.figure(figsize=(14, 9.2))
    gs = fig.add_gridspec(2, 1, height_ratios=[3.2, 1.15], hspace=0.06)
    ax = fig.add_subplot(gs[0])
    axg = fig.add_subplot(gs[1], sharex=ax)

    for i, row in df.iterrows():
        # PHD-first: solid; MTFR-first: hatched
        for xpos, comps, colors, hatch, trans in [
            (x[i] - offset,
             (row["eat_first_diet"], row["eat_first_tech"]),
             (COL_DIET, COL_TECH), None, False),
            (x[i] + offset,
             (row["mtfr_first_tech"], row["mtfr_first_diet"]),
             (COL_TECH, COL_DIET), "////", True),
        ]:
            pos_bottom = neg_bottom = 0.0
            for value, color in zip(comps, colors):
                if not np.isfinite(value) or value == 0:
                    continue
                face = "none" if trans else color
                edge = color if trans else darken(color)
                if value > 0:
                    ax.bar(xpos, value, bottom=pos_bottom, width=bar_width,
                           facecolor=face, edgecolor=edge, linewidth=1.0,
                           hatch=hatch, zorder=3)
                    pos_bottom += value
                else:
                    ax.bar(xpos, value, bottom=neg_bottom, width=bar_width,
                           facecolor=face, edgecolor=edge, linewidth=1.0,
                           hatch=hatch, zorder=3)
                    neg_bottom += value

