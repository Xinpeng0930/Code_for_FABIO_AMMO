def plot_relative(df: pd.DataFrame, outdir: Path):
    n = len(df)
    x = np.arange(n)
    bar_width = 0.36
    group_gap = 0.04
    offset = (bar_width + group_gap) / 2

    total_reduction = {
        "eat_first": -df["eat_first_total"].sum(),
        "mtfr_first": -df["mtfr_first_total"].sum(),
    }

    fig, ax = plt.subplots(figsize=(14, 6.8))
    extents = [0.0]
    for i, row in df.iterrows():
        for position, prefix, hatched in [
            (x[i] - offset, "eat_first", False),
            (x[i] + offset, "mtfr_first", True),
        ]:
            total = total_reduction[prefix]
            if prefix == "eat_first":
                m1, m2 = row["eat_first_diet"], row["eat_first_tech"]
                c1, c2 = COL_DIET, COL_TECH
            else:
                m1, m2 = row["mtfr_first_tech"], row["mtfr_first_diet"]
                c1, c2 = COL_TECH, COL_DIET
            if total == 0:
                s1 = s2 = 0.0
            else:
                s1 = -m1 / total * 100
                s2 = -m2 / total * 100
            extents.extend([s1, s2, s1 + s2])
            pos_bottom = neg_bottom = 0.0
            for value, color in ((s1, c1), (s2, c2)):
                face = "none" if hatched else color
                edge = color if hatched else darken(color)
                if value >= 0:
                    ax.bar(position, value, bottom=pos_bottom,
                           width=bar_width, facecolor=face, edgecolor=edge,
                           linewidth=1.0, hatch="////" if hatched else None,
                           zorder=3)
                    pos_bottom += value
                else:
                    ax.bar(position, value, bottom=neg_bottom,
                           width=bar_width, facecolor=face, edgecolor=edge,
                           linewidth=1.0, hatch="////" if hatched else None,
                           zorder=3)
                    neg_bottom += value

    ymin, ymax = min(extents), max(extents)
    pad = 0.10 * max(abs(ymin), abs(ymax))
    ax.set_xlim(-0.65, n - 0.35)
    ax.set_ylim(ymin - pad, ymax + pad)
