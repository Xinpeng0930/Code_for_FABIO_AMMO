def category_waterfall():
    _rc = plt.rcParams.copy()
    out_dir = UNC_DIR
    data = np.load(os.path.join(out_dir, "MC_Waterfall_Data.npz"), allow_pickle=True)

    eaf_tf = data["eaf_tf"]        # EAT animal with Trade+EF (1000, 8)
    epf_tf = data["epf_tf"]        # EAT plant with Trade+EF (1000, 14)
    cur_af1 = data["cur_af1"]      # Current animal with EF (1000, 8)
    cur_pf1 = data["cur_pf1"]      # Current plant with EF (1000, 14)
    eaf0 = data["eaf0"]            # EAT animal baseline (1000, 8) — deterministic
    epf0 = data["epf0"]            # EAT plant baseline (1000, 14)
    cur_af0 = data["cur_af0"]      # Current animal baseline (1000, 8)
    cur_pf0 = data["cur_pf0"]      # Current plant baseline (1000, 14)
    animal_foods = list(data["animal_foods"])
    plant_foods = list(data["plant_foods"])

    # Deterministic per-food baselines from the "no-T no-EF" vectors (all rows identical)
    eaf_base = eaf0[0]             # (8,)
    epf_base = epf0[0]             # (14,)
    caf_base = cur_af0[0]          # (8,)
    cpf_base = cur_pf0[0]          # (14,)

    # 22-food → 11 waterfall category aggregation (same as #H18)
    GROUPS = [
        ("Pork",                 [("a", 5)]),
        ("Milk or equivalent",   [("a", 1)]),
        ("Beef",                 [("a", 0)]),
        ("Poultry meat & eggs",  [("a", 2), ("a", 6)]),
        ("Other animal products",[("a", 4), ("a", 7)]),
        ("Fats & oils",          [("a", 3), ("p", 11), ("p", 13)]),
        ("Nuts",                 [("p", 5)]),
        ("Legumes",              [("p", 2)]),
        ("Veg & fruits",         [("p", 0), ("p", 4)]),
        ("Whole grains",         [("p", 1), ("p", 6), ("p", 7), ("p", 8), ("p", 9), ("p", 10)]),
        ("Other plant products", [("p", 3), ("p", 12)]),
    ]

    # Fig5 (Manuscriptv27) palette — category colors aligned with the main-text figure
    GROUP_COLORS = {
        "Pork": "#FF6C64", "Milk or equivalent": "#C4003A", "Beef": "#EA0041",
        "Poultry meat & eggs": "#FFAD99", "Other animal products": "#FFE2D7",
        "Fats & oils": "#FF8A27", "Nuts": "#00B96D", "Legumes": "#A3ECB2",
        "Veg & fruits": "#8CC6E2", "Whole grains": "#296AB0", "Other plant products": "#3F94C8",
    }

    # Fig5 display order (left to right): Pork, Milk, Beef, Fats & oils, Other animal,
    # Poultry meat & eggs, Whole grains, Veg & fruits, Legumes, Nuts, Other plant
    FIG5_DELTA_ORDER_NAMES = ["Pork", "Milk or equivalent", "Beef", "Fats & oils",
                              "Other animal products", "Poultry meat & eggs",
                              "Whole grains", "Veg & fruits", "Legumes", "Nuts",
                              "Other plant products"]

    plt.rcParams.update({"font.size": 13, "axes.titlesize": 15, "axes.labelsize": 13,
                         "xtick.labelsize": 10, "ytick.labelsize": 11, "legend.fontsize": 11,
                         "figure.dpi": 200, "savefig.bbox": "tight",
                         "svg.fonttype": "none"})  # keep text editable in SVG

    grp_labels = [g[0] for g in GROUPS]


    def aggregate(af_sims, pf_sims, base_af_vec, base_pf_vec):
        grp_sims_list, grp_base_list = [], []
        for grp_name, members in GROUPS:
            acc = np.zeros(af_sims.shape[0])
            bacc = 0.0
            for src, idx in members:
                if src == "a":
                    acc += af_sims[:, idx]
                    bacc += base_af_vec[idx]
                else:
                    acc += pf_sims[:, idx]
                    bacc += base_pf_vec[idx]
            grp_sims_list.append(acc)
            grp_base_list.append(bacc)
        return np.column_stack(grp_sims_list), np.array(grp_base_list)


    # ---- Current diet (EF only) ----
    cur_sims, cur_base = aggregate(cur_af1, cur_pf1, caf_base, cpf_base)

    # ---- EAT diet (+Trade+EF) ----
    eat_sims, eat_base = aggregate(eaf_tf, epf_tf, eaf_base, epf_base)

    # ---- Delta (paired: EAT +Trade+EF - Current EF) ----
    delta_sims = eat_sims - cur_sims
    delta_base = eat_base - cur_base


    # ================================================================
    # Print tables
    # ================================================================
    def print_table(sims, base, title, show_ci=False):
        print(f"\n{'='*70}")
        print(f"  {title}")
        print(f"{'='*70}")
        header = f"{'Category':<18} {'Base':>8} {'Mean':>8} {'Std':>8} {'CV':>8}"
        if show_ci:
            header += f" {'CI_low':>9} {'CI_high':>9}"
        print(header)
        print("-" * (56 + (22 if show_ci else 0)))
        for i, label in enumerate(grp_labels):
            m, s = sims[:, i].mean(), sims[:, i].std()
            cv = abs(s / m) if abs(m) > 0.01 else 0
            line = f"{label:<18} {base[i]:>8.2f} {m:>8.2f} {s:>8.2f} {cv:>8.4f}"
            if show_ci:
                lo = np.percentile(sims[:, i], 2.5)
                hi = np.percentile(sims[:, i], 97.5)
                line += f" {lo:>9.2f} {hi:>9.2f}"
            print(line)
        t = sims.sum(axis=1)
        tm, ts = t.mean(), t.std()
        tcv = abs(ts / tm) if abs(tm) > 0.01 else 0
        line = f"{'GRAND TOTAL':<18} {base.sum():>8.2f} {tm:>8.2f} {ts:>8.2f} {tcv:>8.4f}"
        if show_ci:
            lo = np.percentile(t, 2.5)
            hi = np.percentile(t, 97.5)
            line += f" {lo:>9.2f} {hi:>9.2f}"
        print(line)

    print_table(cur_sims, cur_base, "Current Diet — EF only (Waterfall Categories)")
    print_table(eat_sims, eat_base, "EAT Diet (+Trade+EF) — Waterfall Categories")
    print_table(delta_sims, delta_base, "Delta (EAT − Current) — Waterfall Categories", show_ci=True)


    # ================================================================
    # Plot function
    # ================================================================
    def waterfall_bar(sims, base, title, fname, ylabel="NH$_3$-N emissions (kt)", show_zero=False,
                      ymax=None, sort_by=None, category_order=None):
        fig, ax = plt.subplots(figsize=(11, 5.5))
        n = len(grp_labels)

        if category_order is not None:
            order = category_order
        else:
            order = np.arange(n)

        sorted_labels = [grp_labels[i] for i in order]
        sorted_sims = sims[:, order]
        sorted_base = base[order]

        x = np.arange(n)
        mf = sorted_sims.mean(axis=0)
        p2p5 = np.percentile(sorted_sims, 2.5, axis=0)
        p97p5 = np.percentile(sorted_sims, 97.5, axis=0)
        colors = [GROUP_COLORS[l] for l in sorted_labels]

        ax.bar(x, mf, color=colors, edgecolor="white", linewidth=0.5, alpha=0.9, label="Mean")
        ax.errorbar(x, mf, yerr=[mf - p2p5, p97p5 - mf], fmt="none", ecolor="#333",
                    capsize=3, linewidth=1, label="95% interval")
        ax.scatter(x, sorted_base, color="#333", s=45, zorder=4, marker="D",
                   edgecolors="white", linewidth=0.5, label="Baseline")

        if show_zero:
            ax.axhline(0, color="#999", linewidth=0.8, linestyle="--")

        ax.set_xticks(x)
        ax.set_xticklabels(sorted_labels, rotation=30, ha="right")
        ax.set_ylabel(ylabel)
        ax.set_title(title)
        ax.legend(loc="upper right", frameon=True, fancybox=True)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)

        if ymax is not None:
            ax.set_ylim(0, ymax)
        elif not show_zero:
            ax.set_ylim(0, None)

        fig.tight_layout()
        fpath = os.path.join(out_dir, fname.rsplit(".", 1)[0] + ".svg")
        fig.savefig(fpath)
        plt.close(fig)
        print(f"Saved: {fname.rsplit('.',1)[0]}.svg")


    # ================================================================
    # Category ordering:
    #   Current & EAT: by descending mean emission value
    #   Delta: fixed Fig5 order (Pork, Milk, Beef, Fats & oils, Other animal,
    #          Poultry meat & eggs, Whole grains, Veg & fruits, Legumes, Nuts,
    #          Other plant products)
    # ================================================================
    order_cur = np.argsort(cur_sims.mean(axis=0))[::-1]
    order_eat = np.argsort(eat_sims.mean(axis=0))[::-1]

    order_delta = np.array([grp_labels.index(n) for n in FIG5_DELTA_ORDER_NAMES])

    # Unified y-scale for Curr and EAT (same as old script)
    ymax_cur = np.percentile(cur_sims, 97.5, axis=0).max()
    ymax_eat = np.percentile(eat_sims, 97.5, axis=0).max()
    ymax_global = max(ymax_cur, ymax_eat) * 1.05

    waterfall_bar(cur_sims, cur_base,
                  "Current diet — NH$_3$ emissions by category (EF only)",
                  "Waterfall_Current.png",
                  ymax=ymax_global)

    waterfall_bar(eat_sims, eat_base,
                  "EAT diet — NH$_3$ emissions by category (+Trade+EF)",
                  "Waterfall_EAT_with_EF.png",
                  ymax=ymax_global)

    waterfall_bar(delta_sims, delta_base,
                  "Delta (EAT \u2212 Current) — by category",
                  "Waterfall_Delta.png",
                  ylabel="\u0394 NH$_3$-N emissions (kt)",
                  show_zero=True,
                  category_order=order_delta)

    print("\nDone.")
    plt.rcParams.update(_rc)


