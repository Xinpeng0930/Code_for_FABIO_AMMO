    def plot_diverging_stacked(ax, x, arrays, colors, labels, width=0.35, offset=0.0, hatch=None, hatch_transparent=False):
        pos_bottoms = Imp_func.np.zeros(len(x))
        neg_bottoms = Imp_func.np.zeros(len(x))
        xp = x + offset

        for data, color, label in zip(arrays, colors, labels):
            pos_mask = data > 0
            neg_mask = data < 0

            fc = 'none' if hatch_transparent else color
            ec = color if hatch_transparent else tuple(c * 0.6 for c in mcolors.to_rgb(color))
            lw = 1

            # positive part
            if pos_mask.any():
                ax.bar(xp[pos_mask], data[pos_mask],
                       width=width, bottom=pos_bottoms[pos_mask],
                       facecolor=fc, edgecolor=ec, label=label, hatch=hatch,
                       linewidth=lw, zorder=2)
                pos_bottoms[pos_mask] += data[pos_mask]

            # negative part
            if neg_mask.any():
                ax.bar(xp[neg_mask], data[neg_mask],
                       width=width, bottom=neg_bottoms[neg_mask],
                       facecolor=fc, edgecolor=ec, label='_nolegend_', hatch=hatch,
                       linewidth=lw, zorder=2)
                neg_bottoms[neg_mask] += data[neg_mask]

