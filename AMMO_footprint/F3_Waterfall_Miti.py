def darken(color: str, factor: float = 0.65):
    rgb = mcolors.to_rgb(color)
    return tuple(c * factor for c in rgb)


def fmt_number(value: float, digits: int = 0) -> str:
    return f"{value:,.{digits}f}".replace("-", "\u2212")


def load_data(csv_path: Path) -> pd.DataFrame:
    df = pd.read_csv(csv_path)
    df["group"] = df["Fig1_plotting_group"].str.replace(
        r"^\d+_", "", regex=True)
    df["eat_first_diet"] = df["Delta_EAT_vs_CURR"]
    df["eat_first_tech"] = df["Delta_EAT_MTFR_vs_EAT"]
    df["eat_first_total"] = df["eat_first_diet"] + df["eat_first_tech"]
    df["mtfr_first_tech"] = df["Delta_MTFR_vs_CURR"]
    df["mtfr_first_diet"] = df["Delta_MTFR_EAT_vs_MTFR"]
    df["mtfr_first_total"] = df["mtfr_first_tech"] + df["mtfr_first_diet"]
    df["order_gap"] = df["mtfr_first_total"] - df["eat_first_total"]
    return df


